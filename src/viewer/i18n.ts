const DICTIONARIES: Record<Locale, Dictionary> = { ko, en, ja, zh };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const dictionary = DICTIONARIES[locale];
  return (key, vars) => {
    const template = dictionary[key] ?? ko[key];
    return vars ? template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match)) : template;
  };
}

function initialLocale(): Locale {
  try {
    const saved = window.localStorage.getItem('sceliph.locale');
    if (saved && saved in DICTIONARIES) return saved as Locale;
  } catch {
    // Storage can be unavailable (private windows); fall through to the browser language.
  }
  const language = (typeof navigator === 'undefined' ? 'ko' : navigator.language).slice(0, 2);
  return language in DICTIONARIES ? language as Locale : 'ko';
}

export function useLocale(): { locale: Locale; setLocale: (locale: Locale) => void; t: Translate } {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  useEffect(() => {
    document.documentElement.lang = locale === 'zh' ? 'zh-Hans' : locale;
  }, [locale]);
  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem('sceliph.locale', next);
    } catch {
      // Remembering the language is a convenience only.
    }
  }, []);
  return { locale, setLocale, t: translator(locale) };
}
